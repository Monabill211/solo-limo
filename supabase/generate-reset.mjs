import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('./', import.meta.url);
const migrations = new URL('migrations/', root);
const versions = (await readdir(migrations)).filter((name) => /^\d+_.+\.sql$/.test(name)).sort();
const prelude = await readFile(new URL('operations/reset-live.sql', root), 'utf8');
const sections = await Promise.all(versions.map(async (version) => {
  const source = (await readFile(new URL(version, migrations), 'utf8')).trim();
  if (!/^begin;\s/i.test(source) || !/\scommit;$/i.test(source)) {
    throw new Error(`Expected transaction wrapper in ${version}`);
  }
  return `-- ${version}\n${source.replace(/^begin;\s*/i, '').replace(/\s*commit;$/i, '')}`;
}));
const output = new URL('reset.generated.sql', root);
await writeFile(output, [
  '-- Generated by node supabase/generate-reset.mjs. Review the target before running.',
  'begin;',
  prelude.trim(),
  ...sections,
  'commit;',
  '',
].join('\n\n'));
console.log(fileURLToPath(output));
